package src.aeropuerto.maria;
/**
 * La enumeración DireccionRelativaCiudad representa las direcciones relativas a la ciudad del aeropuerto.
 * 
 * @author María Pozo, Carmen Gómez, Claudia Municio.
 */
public enum DireccionRelativaCiudad {
    /** Dirección norte en la ciudad*/
    NORTE,
    /** Dirección sur en la ciudad*/
    SUR,
    /** Dirección este en la ciudad*/
    ESTE,
    /** Dirección oeste en la ciudad*/
    OESTE,   
}