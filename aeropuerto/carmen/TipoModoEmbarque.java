package aeropuerto;
/**
 * La enumeración TipoModoEmbarque define si un vuelo embarca mediante
 * finger o zona de aparcamiento.
 * 
 * @author Carmen Gómez, María Pozo, Claudia Municio.
 */
public enum TipoModoEmbarque{
    /** Vuelo que embarca desde un finger */
    FINGER,
    /** Vuelo que embarca desde una zona de aparcamiento */
    ZONA_DE_APARCAMIENTO;
}
