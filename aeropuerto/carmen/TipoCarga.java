package aeropuerto.carmen;
import java.util.*;
/**
 * La enumeración TipoCarga define si un vuelo es de mercancías
 * o de pasajeros.
 * 
 * @author Carmen Gómez, María Pozo, Claudia Municio.
 */
public enum TipoCarga{
    /** El vuelo traslada pasajeros */
    PASAJEROS,
    /** El vuelo traslada mercancia */
    MERCANCIAS;
}
